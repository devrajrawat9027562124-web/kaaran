"""LLM explainer accuracy: how often does Claude state a value that isn't in
the trace, before and after Kaaran's validator?

    python evaluation/explainer_accuracy.py --yes      (from the kaaran folder)

This calls the paid Claude API (ANTHROPIC_API_KEY in backend/.env): three
steps from each of 20 Python programs, at most two requests per step, so up
to 120 requests. It refuses to run without --yes.

For each explanation it records the values Claude mentioned and how many
weren't in the trace, first try and after the validator's one retry, and
writes evaluation/explainer_accuracy.md.
"""
import argparse
import datetime
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "tracer"))
sys.path.insert(0, os.path.join(ROOT, "backend"))

from dotenv import load_dotenv  # noqa: E402

load_dotenv(os.path.join(ROOT, "backend", ".env"))

import explainer  # noqa: E402
from tracer import trace  # noqa: E402
from why import WhyEngine  # noqa: E402

INPUTS = {"13_input.py": "Asha\n19\n", "s16_input.py": "Ravi\n20\n"}
SKIP = {"06_infinite_loop.py"}
STEPS_PER_PROGRAM = 3


def frame_label(frame):
    return "main program" if frame["func"] == "<module>" else f"{frame['func']}()"


def facts_for(result, engine, index):
    """The same facts the frontend sends (frontend/src/traceUtils.ts explainFacts)."""
    steps = result["steps"]
    now = steps[index]
    target = index
    for i in range(index - 1, -1, -1):  # the line that just ran, in the same call
        if steps[i]["frame_id"] == now["frame_id"]:
            target = i
            break
    step = steps[target]
    after = None
    if target != index:
        after = next((f["locals"] for f in now["stack"] if f["frame_id"] == step["frame_id"]), None)
    text = engine.explain_step(step["step"])["text"]
    return {
        "language": "python", "code": result["code"], "step": step["step"], "line": step["line"],
        "event": step["event"], "narration": f"Line {step['line']} ran: {text}.",
        "before": {frame_label(f): f["locals"] for f in step["stack"]},
        "after": after, "output": now["stdout"][-2000:], "why": None,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--yes", action="store_true", help="agree to the API cost")
    args = parser.parse_args()
    if not explainer.available():
        sys.exit("Set ANTHROPIC_API_KEY in backend/.env first.")
    if not args.yes:
        sys.exit("This makes up to 120 paid API requests. Run again with --yes to go ahead.")

    paths = [p for p in sorted(glob.glob(os.path.join(ROOT, "tests/programs/*.py")))
             + sorted(glob.glob(os.path.join(ROOT, "evaluation/slicing/programs/*.py")))
             if os.path.basename(p) not in SKIP][:20]
    explain = explainer.Explainer()
    rows = []
    for path in paths:
        with open(path, encoding="utf-8") as f:
            result = trace(f.read(), INPUTS.get(os.path.basename(path), ""))
        engine = WhyEngine(result)
        line_steps = [i for i, s in enumerate(result["steps"]) if s["event"] == "line" and i > 0]
        picks = sorted({line_steps[int(k * (len(line_steps) - 1) / max(STEPS_PER_PROGRAM - 1, 1))]
                        for k in range(STEPS_PER_PROGRAM)}) if line_steps else []
        for index in picks:
            try:
                answer = explain.explain(facts_for(result, engine, index))
            except explainer.ExplainerError as e:
                rows.append({"program": os.path.basename(path), "step": index + 1, "error": str(e)})
                continue
            rows.append({"program": os.path.basename(path), "step": index + 1,
                         "first_mentioned": answer["first_attempt"]["mentioned"],
                         "first_wrong": answer["first_attempt"]["wrong"],
                         "final_mentioned": len(answer["mentioned_values"]),
                         "final_wrong": len(answer["problems"]),
                         "retried": answer["retried"], "verified": answer["verified"]})
            print(rows[-1])

    done = [r for r in rows if "error" not in r]
    first_m = sum(r["first_mentioned"] for r in done)
    first_w = sum(r["first_wrong"] for r in done)
    final_m = sum(r["final_mentioned"] for r in done)
    final_w = sum(r["final_wrong"] for r in done)
    lines = [
        "# LLM explainer accuracy (generated by evaluation/explainer_accuracy.py)",
        "",
        f"Run on {datetime.date.today().isoformat()} with {os.environ.get('KAARAN_MODEL', 'claude-opus-5-5')}, "
        f"effort {os.environ.get('KAARAN_EFFORT', 'low')}. {len(done)} explanations, {len(rows) - len(done)} failed requests.",
        "",
        "| | Values mentioned | Not in the trace | Correct |",
        "|---|---|---|---|",
        f"| First answer (no validator) | {first_m} | {first_w} | {100 * (1 - first_w / max(first_m, 1)):.1f}% |",
        f"| After the validator's retry | {final_m} | {final_w} | {100 * (1 - final_w / max(final_m, 1)):.1f}% |",
        "",
        f"Explanations shown as checked: {sum(r['verified'] for r in done)}/{len(done)}. "
        f"Retries needed: {sum(r['retried'] for r in done)}.",
        "",
        "Note: the validator only checks values listed in mentioned_values; a value written in the text but "
        "left out of that list isn't caught. Spot-check some explanations by hand.",
    ]
    with open(os.path.join(HERE, "explainer_accuracy.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
