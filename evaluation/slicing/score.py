"""Measure the Why Engine's slice accuracy against hand-labelled answers.

    python evaluation/slicing/score.py            (from the kaaran folder)

For each case in cases.json: trace the program, ask "why does <variable>
have its value?" at the end of the run, and compare the lines Kaaran gives
with the expected lines:

    precision   share of Kaaran's lines that are correct   (extra lines lower it)
    recall      share of the correct lines Kaaran found    (missed lines lower it)
    exact       Kaaran's lines are exactly the expected ones

C cases need gcc and gdb (and tree-sitter); without them they are skipped.
Writes the table to evaluation/slicing/results.md.
"""
import datetime
import json
import os
import platform
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "tracer"))
sys.path.insert(0, os.path.join(ROOT, "backend", "runner"))

from tracer import trace as trace_python  # noqa: E402
from why import WhyEngine  # noqa: E402


def trace_case(case, code):
    if case["program"].endswith(".py"):
        return trace_python(code, case.get("input", ""))
    from c_tracer import trace as trace_c
    language = "cpp" if case["program"].endswith(".cpp") else "c"
    return trace_c(code, language, case.get("input", ""))


def score(case):
    with open(os.path.join(HERE, "programs", case["program"]), encoding="utf-8") as f:
        code = f.read()
    result = trace_case(case, code)
    if result["error"]:
        raise RuntimeError(f"{case['program']}: {result['error']}")
    engine = WhyEngine(result)
    last = max(engine.steps)
    found = set(engine.why(last, case["variable"], -1)["lines"])
    expected = set(case["expected"])
    hits = len(found & expected)
    return {
        "program": case["program"],
        "variable": case["variable"],
        "expected": sorted(expected),
        "found": sorted(found),
        "missed": sorted(expected - found),
        "extra": sorted(found - expected),
        "precision": hits / len(found) if found else 0.0,
        "recall": hits / len(expected),
        "exact": found == expected,
    }


def main():
    with open(os.path.join(HERE, "cases.json"), encoding="utf-8") as f:
        cases = json.load(f)["cases"]
    can_trace_c = all(shutil.which(t) for t in ("gcc", "gdb"))
    rows, skipped = [], []
    for case in cases:
        if not case["program"].endswith(".py") and not can_trace_c:
            skipped.append(case["program"])
            continue
        rows.append(score(case))

    n = len(rows)
    precision = sum(r["precision"] for r in rows) / n
    recall = sum(r["recall"] for r in rows) / n
    exact = sum(r["exact"] for r in rows)

    lines = [
        "# Slice accuracy (generated by evaluation/slicing/score.py)",
        "",
        f"Run on {datetime.date.today().isoformat()}, Python {platform.python_version()}, {platform.system()}.",
        "Labels in cases.json were drafted by the AI assistant and still need checking by a person.",
        "",
        f"**{n} cases**: mean precision **{precision:.2f}**, mean recall **{recall:.2f}**, exact match **{exact}/{n}**."
        + (f" Skipped (no gcc/gdb): {', '.join(skipped)}." if skipped else ""),
        "",
        "| Program | Variable | Expected lines | Kaaran's lines | Missed | Extra | Precision | Recall |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| {r['program']} | `{r['variable']}` | {r['expected']} | {r['found']} | "
                     f"{r['missed'] or ''} | {r['extra'] or ''} | {r['precision']:.2f} | {r['recall']:.2f} |")
    report = "\n".join(lines) + "\n"
    with open(os.path.join(HERE, "results.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(report)
    print(report)


if __name__ == "__main__":
    main()
